const order = (
  id: string,
  folio: string,
  patientId: string,
  prescriptionId: string,
  estado: Order['estado'],
  cristal: Order['cristal'],
  armazon: Order['armazon'],
  abono: number,
  createdAt: string,
  promesa: string,
  recetaComprada = false,
): Order => {
  const bruto = cristal.precio + armazon.precio
  const descuento = recetaComprada ? 15000 : 0
  const total = bruto - descuento
  const historial: Order['historial'] = [
    { estado: 'recepcion', fecha: createdAt, usuario: 'Paula Rivas' },
  ]
  if (estado !== 'recepcion') {
    historial.push({
      estado: 'laboratorio',
      fecha: new Date(new Date(createdAt).getTime() + 3600000).toISOString(),
      usuario: 'Marcos León',
    })
  }
  if (estado === 'montaje' || estado === 'lista' || estado === 'entregada') {
    historial.push({
      estado: 'montaje',
      fecha: new Date(new Date(createdAt).getTime() + 7200000).toISOString(),
      usuario: 'Marcos León',
    })
  }
  if (estado === 'lista' || estado === 'entregada') {
    historial.push({
      estado: 'lista',
      fecha: new Date(new Date(createdAt).getTime() + 86400000).toISOString(),
      usuario: 'Marcos León',
    })
  }
  if (estado === 'entregada') {
    historial.push({
      estado: 'entregada',
      fecha: new Date(new Date(createdAt).getTime() + 172800000).toISOString(),
      usuario: 'Paula Rivas',
    })
  }
  return {
    id,
    folio,
    patientId,
    prescriptionId,
    estado,
    cristal,
    armazon,
    descuento,
    total,
    abono,
    createdAt,
    promesa,
    historial,
    recetaComprada,
  }
}

